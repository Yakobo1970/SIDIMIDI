def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')

here = os.path.dirname(os.path.abspath(__file__))
path = os.path.join(here, '..', 'Source', 'Lang.cpp')
text = open(path, encoding='utf-8', newline='').read()
crlf = '\r\n' in text
head, rest = text.split('// ---- table begin')
_, tail = rest.split('// ---- table end')
seen = set()
lines = []
for de, en, fr in ROWS:
    if de in seen:
        continue
    seen.add(de)
    lines.append('    { "%s", "%s", "%s" },' % (esc(de), esc(en), esc(fr)))
body = '\nconst Row kRows[] = {\n' + '\n'.join(lines) + '\n    '
if crlf:
    body = body.replace('\n', '\r\n')
open(path, 'w', encoding='utf-8', newline='').write(head + '// ---- table begin' + body + '// ---- table end' + tail)
print(len(lines), 'Zeilen geschrieben')
